"""文本规范化工具（ADR-040：字幕文本单行不变量）。

字幕文本必须**单行**——断行属于剪辑软件的表现层职责，程序不应把译文里的
分行带进字幕。`srt_utils.block` 的换行完全由调用方传入的 ``lines`` 决定，
因此任何文本内容里的 ``\\n`` 都会直接变成字幕里的额外行（用户报告的
「单语 zh.srt / en.srt 里也有换行」）。

本模块是纯函数、无 I/O，供各个 **write 边界**（transcribe / translate /
generate）统一调用，保证落到产物文件里的文本干净（ADR-035 D4 边界校验）。
"""
from __future__ import annotations

import re

# 换行（含其两侧的水平空白）→ 单空格。
# 有意用 ``[ \t]*`` 而非 ``\s*``：只吸收换行两侧的空格/制表符，不吞并正文里
# 的其他空白（例如中文全角空格）。
_LINEBREAK_RE = re.compile(r"[ \t]*[\r\n]+[ \t]*")


def to_single_line(text: str) -> str:
    """把文本压成单行（ADR-040 D3）：换行 → 单空格，去首尾。

    规则：
      * 连续换行（``\\n\\n``）压成**一个空格** —— 保留句子间隔，不粘连内容；
      * 换行两侧的空格 / 制表符一并吸收 —— 避免产生双空格；
      * **不动正文其他空白**，也绝不触碰时间戳（ADR-012）。

    对中英文统一：英文需要空格以免单词粘连；中文得到「你好 世界」式单行，
    比直接删除更无损。纯函数，无 I/O。
    """
    if not text:
        return ""
    return _LINEBREAK_RE.sub(" ", text).strip()
